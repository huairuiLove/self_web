export function getPaperBySlug(slug: string): ResearchPaper | undefined {
  return papers.find((paper) => paper.slug === slug)
}

export function getPaperUrl(paper: ResearchPaper): string {
  return paper.arxivId || paper.localPdf ? `/papers/${paper.slug}` : paper.externalUrl ?? '#'
}

export function getPaperPdfUrl(paper: ResearchPaper): string | undefined {
  const fileName = paper.localPdf ?? (paper.arxivId ? `${paper.arxivId}.pdf` : undefined)
  return fileName ? `/papers/${fileName}` : undefined
}
